#pragma once

/* ISO15693 request flags, commands, errors and SLIX password identifiers. */
#define ISO15693_REQ_DUAL_SUBCARRIER 0x01u
#define ISO15693_REQ_HIGH_RATE 0x02u
#define ISO15693_REQ_INVENTORY 0x04u
#define ISO15693_REQ_SELECT 0x10u
#define ISO15693_REQ_ADDRESS 0x20u
#define ISO15693_REQ_OPTION 0x40u
#define ISO15693_REQ_AFI 0x10u
#define ISO15693_REQ_SLOT1 0x20u

#define ISO15693_RES_OK 0x00u
#define ISO15693_RES_ERROR 0x01u

#define ISO15693_ERR_CMD_NOT_SUPPORTED 0x01u
#define ISO15693_ERR_GENERIC 0x0fu
#define ISO15693_ERR_BLOCK_UNAVAILABLE 0x10u
#define ISO15693_ERR_BLOCK_ALREADY_LOCKED 0x11u
#define ISO15693_ERR_BLOCK_LOCKED 0x12u

#define ISO15693_CMD_INVENTORY 0x01u
#define ISO15693_CMD_STAY_QUIET 0x02u
#define ISO15693_CMD_READ_SINGLE 0x20u
#define ISO15693_CMD_WRITE_SINGLE 0x21u
#define ISO15693_CMD_LOCK_BLOCK 0x22u
#define ISO15693_CMD_READ_MULTIPLE 0x23u
#define ISO15693_CMD_SELECT 0x25u
#define ISO15693_CMD_RESET_TO_READY 0x26u
#define ISO15693_CMD_WRITE_AFI 0x27u
#define ISO15693_CMD_LOCK_AFI 0x28u
#define ISO15693_CMD_WRITE_DSFID 0x29u
#define ISO15693_CMD_LOCK_DSFID 0x2au
#define ISO15693_CMD_GET_SYSTEM_INFO 0x2bu
#define ISO15693_CMD_GET_BLOCK_SECURITY 0x2cu

#define ISO15693_CMD_CUSTOM_MIN 0xa0u
#define ISO15693_CMD_CUSTOM_MAX 0xdfu

#define ISO15693_CMD_NXP_SET_EAS 0xa2u
#define ISO15693_CMD_NXP_RESET_EAS 0xa3u
#define ISO15693_CMD_NXP_LOCK_EAS 0xa4u
#define ISO15693_CMD_NXP_EAS_ALARM 0xa5u
#define ISO15693_CMD_NXP_PASSWORD_PROTECT_EAS_AFI 0xa6u
#define ISO15693_CMD_NXP_GET_RANDOM_NUMBER 0xb2u
#define ISO15693_CMD_NXP_SET_PASSWORD 0xb3u
#define ISO15693_CMD_NXP_WRITE_PASSWORD 0xb4u
#define ISO15693_CMD_NXP_DESTROY 0xb9u
#define ISO15693_CMD_NXP_ENABLE_PRIVACY 0xbau

/* NXP SLIX password identifiers */
#define SLIX_PASSWORD_READ 0x01u
#define SLIX_PASSWORD_WRITE 0x02u
#define SLIX_PASSWORD_PRIVACY 0x04u
#define SLIX_PASSWORD_DESTROY 0x08u
#define SLIX_PASSWORD_EAS_AFI 0x10u
