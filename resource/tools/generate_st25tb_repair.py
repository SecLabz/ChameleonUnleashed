"""Generate the finite ST25TB start-rise repair class from the shared CRC."""
import argparse
import bisect
from collections import defaultdict
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
RFID = ROOT / 'firmware/application/src/rfid'
OUTPUT = RFID / 'st25tb/repair_data.h'

# Rows are payload distance from the CRC, then the two wire CRC bytes.
PROBE = r'''
#include "iso15693/frame.h"
#include <stdio.h>
int main(void) {
    uint8_t data[6] = {0};
    for (unsigned length = 1; length <= sizeof(data); length++) {
        data[0] = 0;
        uint16_t original = iso15693_crc16(data, length);
        for (unsigned bits = 1; bits <= 7; bits++) {
            data[0] = (1u << bits) - 1;
            printf("%u\n", original ^ iso15693_crc16(data, length));
        }
    }
    for (unsigned byte = 0; byte < ISO15693_CRC_SIZE; byte++) {
        for (unsigned bits = 1; bits <= 7; bits++) {
            printf("%u\n", ((1u << bits) - 1) << (8 * byte));
        }
    }
}
'''


def generate():
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory)
        source = path / 'effects.c'
        binary = path / 'effects'
        source.write_text(PROBE)
        subprocess.run([
            'cc', '-std=c11', '-Wall', '-Wextra', '-Werror',
            '-I', str(RFID), str(source), str(RFID / 'iso15693/frame.c'),
            '-o', str(binary),
        ], check=True)
        effects = [int(value) for value in subprocess.check_output([binary], text=True).split()]
    assert len(effects) == len(set(effects)) == 56 and 0 not in effects

    choices = defaultdict(list)
    previous = []
    for row in (5, 4, 3, 2, 1, 0, 6, 7):
        for bit in range(7):
            current = row * 7 + bit
            choices[effects[current]].append(current + 1)
            for earlier in previous:
                code = (current + 1) | ((earlier + 1) << 6)
                choices[effects[current] ^ effects[earlier]].append(code)
        # A pair must affect different bytes; the current row is added last.
        previous.extend(range(row * 7, row * 7 + 7))
    assert 0 not in choices and len(choices) == 1416
    assert sum(map(len, choices.values())) == 1428
    assert max(map(len, choices.values())) == 2
    keys = sorted(choices)
    limits = [bisect.bisect_left(keys, high << 8) for high in range(257)]
    lines = [
        '/* Generated by resource/tools/generate_st25tb_repair.py; do not edit.',
        ' * Choices retain wire-byte/run order. Each one-based six-bit symbol',
        ' * encodes a CRC-relative byte and a contiguous low-bit mask. */',
        '_Static_assert(ST25TB_REQUEST_MAX == 8 && STB_RX_RUN_MAX_BITS == 9 && ISO15693_CRC_SIZE == 2,',
        '               "Regenerate the repair class when request or run bounds change");',
        '',
        'static const repair_entry_t repair_entries[] = {',
    ]
    for error in keys:
        first, *rest = choices[error]
        second = rest[0] if rest else 0
        lines.append(f'    {{0x{error:04x}u, {{0x{first:04x}u, 0x{second:04x}u}}}},')
    lines.extend(['};', '', '/* Restrict each lookup to its CRC high-byte range. */',
                  'static const uint16_t repair_limits[257] = {'])
    for start in range(0, len(limits), 12):
        lines.append('    ' + ', '.join(map(str, limits[start:start + 12])) + ',')
    lines.extend(['};', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in table differs')
    args = parser.parse_args()
    data = generate()
    if args.check:
        if OUTPUT.read_text() != data:
            parser.exit(1, f'{OUTPUT} needs regeneration\n')
    else:
        OUTPUT.write_text(data)


if __name__ == '__main__':
    main()
